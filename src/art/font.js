export const FONT_CHARS = ' !"#$%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~';
export const FONT_CELL_W = 6;
export const FONT_CELL_H = 8;
export const FONT_PER_ROW = 16;

// Build the glyph sheet as a Pix (white glyphs on transparent, tint them in-game)
export function buildFontSheet() {
  const rows = Math.ceil(FONT_CHARS.length / FONT_PER_ROW);
  const sheet = new Pix(FONT_PER_ROW * FONT_CELL_W, rows * FONT_CELL_H);
  [...FONT_CHARS].forEach((ch, i) => {
    const key = ch in G ? ch : ch.toUpperCase() in G ? ch.toUpperCase() : '?';
    if (ch === ' ') return;
    const glyph = G[key];
    const ox = (i % FONT_PER_ROW) * FONT_CELL_W;
    const oy = Math.floor(i / FONT_PER_ROW) * FONT_CELL_H;
    glyph.forEach((row, y) => [...row].forEach((px, x) => { if (px === '#') sheet.set(ox + x, oy + y, '#ffffff'); }));
  });
  return sheet;
}
